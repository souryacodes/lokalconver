"""Write precache-manifest.js: the list of app shell files for the service worker.

Run from the repo root before every deploy:   python tools/gen_precache.py
Check only (for tests and CI, changes nothing): python tools/gen_precache.py --check

Why a script: the website has no build step, and a hand-written file list gets
out of date. This reads the real files, so nothing is forgotten. The version is
a hash of the file contents, so the cache name changes exactly when a file does.

Left out on purpose: everything in js/vendor/ (the engines), the PNG icons and
any file over 150 KB. They are cached the first time they are used, so the first visit stays small.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import sys
from fnmatch import fnmatch
from pathlib import Path

OUTPUT = "precache-manifest.js"
ROOT_FILES = ["index.html", "manifest.webmanifest"]
# Folders that hold the app shell. Tests, tools, docs, samples, dev/ and the
# generated convert/ pages are not part of it.
SHELL_DIRS = ["css", "js", "locales", "assets"]
# Left out of the shell on purpose:
# - Engines (js/vendor/) are big and used rarely. The service worker saves each
#   one the first time a conversion asks for it.
# - The PNG icons are used only by the phone when the app is installed (which needs
#   the internet anyway). They would add about 55 KB to the first visit for nothing.
EXCLUDED_PATTERNS = ("js/vendor/*", "assets/icons/*.png")
EXTENSIONS = {
    ".html", ".css", ".js", ".mjs", ".json", ".svg", ".png", ".webp",
    ".ico", ".woff2", ".webmanifest",
}
TEXT_EXTENSIONS = {".html", ".css", ".js", ".mjs", ".json", ".svg", ".webmanifest"}
DEFAULT_MAX_FILE_KB = 150
DEFAULT_BUDGET_KB = 200  # first page load budget from AGENTS.md


def list_shell_files(root: Path) -> list[str]:
    """Return sorted, forward-slash paths of the files that belong in the shell."""
    found: list[Path] = [root / name for name in ROOT_FILES if (root / name).is_file()]
    for folder in SHELL_DIRS:
        base = root / folder
        if base.is_dir():
            found.extend(p for p in base.rglob("*") if p.is_file())
    keep = [p for p in found if p.suffix.lower() in EXTENSIONS]
    names = {p.relative_to(root).as_posix() for p in keep}
    return sorted(n for n in names if not any(fnmatch(n, pat) for pat in EXCLUDED_PATTERNS))


def read_for_hash(path: Path) -> bytes:
    """File bytes, with Windows line endings made the same as Linux ones."""
    data = path.read_bytes()
    if path.suffix.lower() in TEXT_EXTENSIONS:
        data = data.replace(b"\r\n", b"\n")
    return data


def build(root: Path, max_file_kb: int = DEFAULT_MAX_FILE_KB) -> tuple[dict, list[str], int]:
    """Return (manifest dict, skipped big files, estimated gzip bytes)."""
    files: list[str] = []
    skipped: list[str] = []
    digest = hashlib.sha256()
    gzip_total = 0
    for rel in list_shell_files(root):
        data = read_for_hash(root / rel)
        if len(data) > max_file_kb * 1024:
            skipped.append(rel)
            continue
        files.append(rel)
        digest.update(rel.encode() + b"\0" + data + b"\0")
        gzip_total += len(gzip.compress(data, 9))
    return {"version": digest.hexdigest()[:10], "files": files}, skipped, gzip_total


def render(manifest: dict) -> str:
    body = json.dumps(manifest, indent=2)
    return (
        "// GENERATED by tools/gen_precache.py. Do not edit by hand.\n"
        f"self.LOKALCONVER_PRECACHE = {body};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."), help="repo root")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    parser.add_argument("--max-file-kb", type=int, default=DEFAULT_MAX_FILE_KB)
    args = parser.parse_args(argv)

    manifest, skipped, gzip_bytes = build(args.root, args.max_file_kb)
    text = render(manifest)
    target = args.root / OUTPUT

    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != text:
            print(f"{OUTPUT} is out of date. Run: python tools/gen_precache.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date (version {manifest['version']}).")
        return 0

    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}: {len(manifest['files'])} files, version {manifest['version']}")
    print(f"estimated shell download: about {gzip_bytes / 1024:.0f} KB gzipped")
    if gzip_bytes > DEFAULT_BUDGET_KB * 1024:
        print(f"WARNING: over the {DEFAULT_BUDGET_KB} KB budget. Tell the owner.", file=sys.stderr)
    for rel in skipped:
        print(f"skipped (over {args.max_file_kb} KB, cached on first use): {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
